// =============================================================
//  calm forest · 🚫 소재 차단 규칙 (뉴스 · 커뮤니티 공용)
//  ------------------------------------------------------------
//  news.mjs(구글 뉴스)와 topics.mjs(커뮤니티)가 같은 규칙을 써야 한다.
//  두 벌로 갈라 두면 한쪽만 느슨해지고, 그 한쪽으로 사고가 난다.
//
//  규칙의 근거는 전부 실제 수집에서 걸러낸 사례다 — 아래 주석 참고.
// =============================================================

/**
 * 🚫 게임 홍보를 붙이면 안 되는 소재. 누군가의 피해·죽음·분쟁 위에
 *    "숲에서 쉬어가세요"를 얹는 순간 계정이 끝난다. 애매하면 버린다.
 */
export const BLOCK = new RegExp([
  '사망|숨진|숨져|자살|극단적|부고|유족|장례',
  '산재|사고|화재|붕괴|추락|참사|테러|전쟁|지진|태풍|실종',
  '폭행|성희롱|성추행|성범죄|성폭력|괴롭힘|갑질|학대|살인|살해',
  // 2차 수집: '직장인 설문' 상위가 통째로 일터 성범죄 조사였다. 피해 서사 전반을 막는다.
  '피해자|2차 피해|피해 우려',
  '고소|고발|소송|구속|검찰|경찰|기소|징계|수사',
  '해고|정리해고|파업|분신|감염|확진',
  // 1차 수집에서 "우울증으로 번졌다… 침묵의 살인마"가 통과했다.
  // 정신건강 질환은 게임 홍보를 붙일 소재가 아니다.
  '우울증|공황|불면증|정신질환|자해|중독',
].join('|'));

/**
 * 🔇 연예·드라마 PR. "직장인" 키워드를 가장 많이 잠식한다.
 *    1차 수집에서 '직장인 번아웃' 상위 21건 중 11건이 드라마 한 편 홍보였다.
 */
export const NOISE = new RegExp([
  '드라마|영화|배우|출연|캐스팅|예능|OST|화보|아이돌|가수|앨범|연예',
  '\\[.*?현장\\]|\\[리뷰|\\[영상\\]|\\[포토|종합\\)|★',
  '브런치',   // 개인 에세이 — 뉴스가 아니다
].join('|'));

/** 🎰 도박 SEO 스팸 */
export const SPAM = /카지노|슬롯|바카라|토토|베팅|벳|도박|먹튀|룰렛|포커|배팅|꽁머니/;

/**
 * 🗳️ 정치·시사. 커뮤니티 랭킹에서만 쏟아진다(뉴스 쿼리엔 거의 없어 news.mjs 엔 없던 규칙).
 *    실측: 디시 실시간 베스트 상위 10건 중 3건이 정당·인사 공방이었다.
 *    어느 편을 들어도 게임 계정이 정치 계정이 된다 — 통째로 버린다.
 */
export const POLITICS = new RegExp([
  '대통령|정부|여당|야당|민주당|국민의힘|의원|장관|청문회|국회|대선|총선',
  '윤석열|이재명|한동훈|추미애|트럼프|푸틴|바이든',
  '정치|보수|진보|좌파|우파|탄핵|특검|개헌',
].join('|'));

/** 🔞 성적 소재 — 커뮤니티 랭킹 단골이다 */
export const ADULT = /누드|섹스|야짤|19금|성인물|노출|몸매|비키니|가슴|엉덩이/;

/**
 * 🚯 혐오·비하. 본문까지 긁으면서 드러났다 — 제목은 뉴스처럼 멀쩡한데
 *    본문(댓글 포함)이 지역 비하 덩어리인 글이 실시간베스트 상위에 있었다.
 *    제목만 보고 통과시키면 그대로 소재 후보에 오른다.
 */
export const HATE = new RegExp([
  '홍어|전라도 1찍|과학이다|광주=|틀딱|급식충|맘충|한남|김치녀|된장녀',
  '짱깨|쪽바리|흑형|조선족 새끼|외노자',
  '병신|애미|애비|씨발|좆|새끼들|ㅅㅂ|ㅄ|ㅗ|뒤져|꺼져',
].join('|'));

/** 🧹 목록에서 딸려 오는 부스러기(댓글 수, 안내 공지 등) */
export const JUNK = /^\[\d+(\/\d+)?\]$|^\d+$|이용 안내|공지사항|운영 원칙/;

/** 쓸 수 있는 소재인가. 버릴 이유가 있으면 그 이유를 돌려준다(없으면 null) */
export function rejectReason(text) {
  const t = (text || '').trim();
  if (!t || t.length < 6) return '너무 짧음';
  if (JUNK.test(t)) return '목록 부스러기';
  if (BLOCK.test(t)) return '피해·사건';
  if (POLITICS.test(t)) return '정치';
  if (ADULT.test(t)) return '성인';
  if (HATE.test(t)) return '혐오·비하';
  if (SPAM.test(t)) return '도박 스팸';
  if (NOISE.test(t)) return '연예 PR';
  return null;
}
