/** 발광색 채널을 0xd9 이하로 눌러 블룸 임계(0.85)를 넘지 않게 — 색조는 유지. */
const toGlow = (h) => { const ch = [(h >> 16) & 255, (h >> 8) & 255, h & 255], m = Math.max(...ch), f = m > 0xd9 ? 0xd9 / m : 1; return (Math.floor(ch[0] * f) << 16) | (Math.floor(ch[1] * f) << 8) | Math.floor(ch[2] * f); };
/** 색을 어둡게(f<1) — 같은 색 계열의 결·그늘에 쓴다. */
const shade = (h, f) => (Math.floor(((h >> 16) & 255) * f) << 16) | (Math.floor(((h >> 8) & 255) * f) << 8) | Math.floor((h & 255) * f);

