//  고정 0.075 는 발 작은 🐰토끼에선 자루가 앞 가장자리에 걸려 발바닥이 뒤에서 감싸 쥔 모양이 됐지만,
//  발 큰 🐻곰·🐼판다에선 자루가 발바닥 한가운데에 묻혔다(2026-09-28 사용자 지적).
//  → 토끼 비율(발바닥 반지름 × 0.67)을 모든 캐릭터에 쓴다. sims/tool-grip-sim.html 검수.
