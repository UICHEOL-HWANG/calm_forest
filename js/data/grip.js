/** 팔 조형의 굵기·발바닥 배율 — game.js buildAnimalMesh 의 mkArm 과 같은 값(한 곳에서만 정한다) */
export const ARM_R_K = 0.23;
export const PAW_K = 1.06;

/** 자루 앞 오프셋 = 발바닥 반지름 × 이 값. 토끼(bodyR .46)에서 기존 0.075 와 같아진다 */
export const GRIP_PAW_K = 0.67;

/** 발바닥 반지름 — 몸 반지름 × 0.23 × 1.06 */
export function pawRadius(bodyR) {
  return bodyR * ARM_R_K * PAW_K;
}

/** 긴 도구 자루를 발바닥 앞으로 빼는 거리(쥐는 자세 회전 뒤 도구 로컬 z) */
export function gripForwardZ(bodyR) {
  return pawRadius(bodyR) * GRIP_PAW_K;
}
